const g = require("../../src/gate_semantic.js");
let passed = 0, failed = 0;
const failures = [];
function run(id, text, shouldPass, description) {
  const result = g.gateSemantic(text);
  const ok = result.passed === shouldPass;
  if (ok) { passed++; console.log("✅ T" + id + ": " + description); }
  else {
    failed++;
    console.log("❌ T" + id + ": " + description);
    console.log("   Input: \"" + text + "\"");
    console.log("   Expected: " + shouldPass + ", Got: " + result.passed + ", V: " + JSON.stringify(result.violations));
    failures.push({ id, text, expected: shouldPass, got: result.passed });
  }
}
